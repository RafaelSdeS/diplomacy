<h1>Aviso de privacidade</h1>
<p class="telegrama" role="note">
	Rascunho. O texto final é combinado com a organização do UFRGSMUN, que é a controladora dos dados.
</p>

<section aria-labelledby="t-o-que">
	<h2 id="t-o-que">O que o app guarda</h2>
	<ul>
		<li><strong>Da inscrição:</strong> nome, e-mail, papel no evento, comitê e delegação. Nada de telefone, endereço ou documentos.</li>
		<li><strong>Do perfil, se você quiser:</strong> uma foto e uma minibiografia.</li>
		<li><strong>Da simulação:</strong> o que você escreve no app (notas de crise, bilhetes, mensagens à mesa, documentos, matérias, cartas), com a autoria.</li>
		<li><strong>Do evento:</strong> presença (check-in) e o certificado.</li>
	</ul>
</section>

<section aria-labelledby="t-para-que">
	<h2 id="t-para-que">Para quê</h2>
	<p>Só para fazer a simulação acontecer e emitir os certificados. Nada é vendido nem usado para propaganda.</p>
</section>

<section aria-labelledby="t-quem-ve">
	<h2 id="t-quem-ve">Quem vê o quê</h2>
	<ul>
		<li>Quem está no mesmo comitê vê o seu nome e o seu papel; a secretaria do evento vê os participantes.</li>
		<li>Notas de crise: só a sua delegação e a equipe de crise do comitê.</li>
		<li>
			Bilhetes: só quem envia e quem recebe. A mesa do comitê pode ler os bilhetes se ligar essa regra, que aparece para
			todos na tela de mensagens, e lê os bilhetes denunciados.
		</li>
		<li>Matérias da press: todo o evento, depois de publicadas.</li>
		<li>Certificados: qualquer pessoa confere, pelo código, o nome, o evento e a função. Nada mais.</li>
	</ul>
</section>

<section aria-labelledby="t-prazo">
	<h2 id="t-prazo">Por quanto tempo</h2>
	<p>
		No prazo combinado com a organização depois do evento, as contas, os e-mails e tudo o que é privado são apagados.
		Ficam só os documentos públicos (resoluções, notícias publicadas, agenda) e os certificados.
	</p>
</section>

<section aria-labelledby="t-direitos">
	<h2 id="t-direitos">Seus direitos</h2>
	<p>
		Em <a href="/perfil/meus-dados">Perfil → Meus dados</a>, você baixa tudo o que o app guarda sobre você, corrige o seu
		nome e pede a exclusão da sua conta.
	</p>
</section>
